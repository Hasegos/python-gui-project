# ─────────────────────────────────────
# 1. 공통 도메인 예외
# ─────────────────────────────────────
class LibraryError(Exception):
    """
    사용자에게 그대로 안내해야 하는 업무 오류.

    화면(templates)에서는 경고 메시지 박스로 표시한다.
    """


# ─────────────────────────────────────
# 2. 입력값 검증 실패
# ─────────────────────────────────────
class ValidationError(LibraryError):
    """필수값 누락, 형식 오류, 중복 값 등 입력값 검증에 실패했을 때 발생한다."""


# ─────────────────────────────────────
# 3. 대상 데이터 없음
# ─────────────────────────────────────
class NotFoundError(LibraryError):
    """수정/삭제/대출 대상 데이터가 존재하지 않을 때 발생한다."""
